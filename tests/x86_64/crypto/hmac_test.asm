    mov rax, SYS_EXIT
    mov rdi, 1
    syscall

expect:
    push rbx
    push r12
    push r13
    mov r12, rdi
    mov r13, rsi
    mov rbx, rdx
0:
    test rbx, rbx
    jz 1f
    mov rax, [r12]
    mov rcx, [r13]
    cmp rax, rcx
    jne fail
    add r12, 8
    add r13, 8
    sub rbx, 8
    jmp 0b
1:
    pop r13
    pop r12
    pop rbx
    ret

