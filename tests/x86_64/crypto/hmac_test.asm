.macro HMC alg, key, keylen, msg, mlen, exp, dlen
    lea rdi, [rip + \key]
    mov rsi, \keylen
    lea rdx, [rip + \msg]
    mov rcx, \mlen
    lea r8, [rip + mac]
    call \alg
    lea rdi, [rip + mac]
    lea rsi, [rip + \exp]
    mov rdx, \dlen
    call expect
.endm

