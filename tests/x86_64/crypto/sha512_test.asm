# SHA-384/SHA-512 tests: FIPS 180-4 vectors plus buffering/partitioning checks.
# exit 0 on success, 1 on failure.

.global _start

.section .text
_start:
    # SHA-512: empty
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_empty]
    mov rdx, 64
    call expect

    # SHA-512: "abc"
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_abc]
    mov rdx, 3
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_abc]
    mov rdx, 64
    call expect

    # SHA-512: "abc" byte by byte
    lea rdi, [rip + ctx]
    call sha512_init
    lea rbx, [rip + msg_abc]
    mov r12, 0
1:
    cmp r12, 3
    jae 2f
    lea rdi, [rip + ctx]
    lea rsi, [rbx + r12]
    mov rdx, 1
    call sha512_update
    add r12, 1
    jmp 1b
2:
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_abc]
    mov rdx, 64
    call expect

    # SHA-512: 448-bit message single call
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_448]
    mov rdx, 56
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_448]
    mov rdx, 64
    call expect

    # SHA-512: 100-byte message
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_100]
    mov rdx, 100
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_100]
    mov rdx, 64
    call expect

    # SHA-512: 200-byte single vs 60+140
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_200]
    mov rdx, 200
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + ctx2]
    call sha512_init
    lea rdi, [rip + ctx2]
    lea rsi, [rip + msg_200]
    mov rdx, 60
    call sha512_update
    lea rdi, [rip + ctx2]
    lea rsi, [rip + msg_200 + 60]
    mov rdx, 140
    call sha512_update
    lea rdi, [rip + ctx2]
    lea rsi, [rip + digest2]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + digest2]
    mov rdx, 64
    call expect

    # SHA-512: one million 'a'
    lea rdi, [rip + msg_a]
    mov rcx, 1000000
    mov rax, 0x6161616161616161
3:
    mov [rdi], rax
    add rdi, 8
    sub rcx, 8
    jnz 3b
    lea rdi, [rip + ctx]
    call sha512_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_a]
    mov rdx, 1000000
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_512_1ma]
    mov rdx, 64
    call expect

    # SHA-384: empty
    lea rdi, [rip + ctx]
    call sha384_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_384_empty]
    mov rdx, 48
    call expect

    # SHA-384: "abc"
    lea rdi, [rip + ctx]
    call sha384_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_abc]
    mov rdx, 3
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_384_abc]
    mov rdx, 48
    call expect

    # SHA-384: 200-byte message
    lea rdi, [rip + ctx]
    call sha384_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_200]
    mov rdx, 200
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_384_200]
    mov rdx, 48
    call expect

    # SHA-384: one million 'a'
    lea rdi, [rip + ctx]
    call sha384_init
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_a]
    mov rdx, 1000000
    call sha512_update
    lea rdi, [rip + ctx]
    lea rsi, [rip + digest]
    call sha512_final
    lea rdi, [rip + digest]
    lea rsi, [rip + expect_384_1ma]
    mov rdx, 48
    call expect

    # all good
    mov rax, SYS_EXIT
    mov rdi, 0
    syscall

fail:
    mov rax, SYS_EXIT
    mov rdi, 1
    syscall

# expect(rdi=got, rsi=want, rdx=len) - exit 1 on mismatch
expect:
    push rbx
    push r12
    push r13
    mov r12, rdi
    mov r13, rsi
    mov rbx, rdx
0:
    test rbx, rbx
    jz 1f
    mov rax, [r12]
    mov rcx, [r13]
    cmp rax, rcx
    jne fail
    add r12, 8
    add r13, 8
    sub rbx, 8
    jmp 0b
1:
    pop r13
    pop r12
    pop rbx
    ret

