# AES-128/256 FIPS 197 schedule, encryption and decryption tests.

.global _start

.macro CHECK dat, exp, n
    lea rdi, [rip + \dat]
    lea rsi, [rip + \exp]
    mov rdx, \n
    call expect
.endm

.section .text
_start:
    # AES-128 key expansion vs FIPS 197 A.1
    lea rdi, [rip + key128a]
    lea rsi, [rip + sched128]
    call aes128_expand
    CHECK sched128, exp_sched128a, 176

    # AES-128 encrypt of the A.1 plaintext
    lea rdi, [rip + sched128]
    lea rsi, [rip + pt_a1]
    lea rdx, [rip + out]
    call aes128_encrypt
    CHECK out, exp_ct_a1, 16

    # AES-128 decrypt round-trip, overlapping in and out
    lea rdi, [rip + sched128]
    lea rsi, [rip + out]
    lea rdx, [rip + out]
    call aes128_decrypt
    CHECK out, pt_a1, 16

    # AES-128, C.1 key, via the shared aes_encrypt with ecx=10
    lea rdi, [rip + key128b]
    lea rsi, [rip + sched128]
    call aes128_expand
    lea rdi, [rip + sched128]
    lea rsi, [rip + pt_c1]
    lea rdx, [rip + out]
    mov ecx, 10
    call aes_encrypt
    CHECK out, exp_ct_c1, 16

    # AES-256 key expansion vs FIPS 197 A.3
    lea rdi, [rip + key256]
    lea rsi, [rip + sched256]
    call aes256_expand
    CHECK sched256, exp_sched256, 240

    # AES-256 encrypt of the C.3 plaintext
    lea rdi, [rip + sched256]
    lea rsi, [rip + pt_c3]
    lea rdx, [rip + out]
    call aes256_encrypt
    CHECK out, exp_ct_c3, 16

    # AES-256 decrypt round-trip, overlapping in and out
    lea rdi, [rip + sched256]
    lea rsi, [rip + out]
    lea rdx, [rip + out]
    call aes256_decrypt
    CHECK out, pt_c3, 16

    mov rax, SYS_EXIT
    mov rdi, 0
    syscall

fail:
    mov rax, SYS_EXIT
    mov rdi, 1
    syscall

expect:
    push rbx
    push r12
    push r13
    mov r12, rdi
    mov r13, rsi
    mov rbx, rdx
0:
    test rbx, rbx
    jz 1f
    mov rax, [r12]
    mov rcx, [r13]
    cmp rax, rcx
    jne fail
    add r12, 8
    add r13, 8
    sub rbx, 8
    jmp 0b
1:
    pop r13
    pop r12
    pop rbx
    ret

