# HKDF-SHA256/SHA384/SHA512 extract + expand tests.
# SHA-256 cases are the official RFC 5869 test vectors; SHA-384/SHA-512
# vectors are generated with Python and cross-checked against OpenSSL's
# `openssl kdf HKDF`. Exit 0 on success, 1 on failure.

.global _start

.macro HKDF_CHECK extractfn, expandfn, ikm, ikmlen, salt, saltlen, info, infolen, outlen, prk, okm, hlen
    lea rdi, [rip + \salt]
    mov rsi, \saltlen
    lea rdx, [rip + \ikm]
    mov rcx, \ikmlen
    lea r8, [rip + prkbuf]
    call \extractfn
    lea rdi, [rip + prkbuf]
    lea rsi, [rip + \prk]
    mov rdx, \hlen
    call expect_b
    lea rdi, [rip + prkbuf]
    lea rsi, [rip + \info]
    mov rdx, \infolen
    lea rcx, [rip + okmbuf]
    mov r8, \outlen
    call \expandfn
    lea rdi, [rip + okmbuf]
    lea rsi, [rip + \okm]
    mov rdx, \outlen
    call expect_b
.endm

.macro HKDF_EL_CHECK fn, secret, label, labellen, context, ctxlen, outlen, expect
    lea rdi, [rip + \secret]
    lea rsi, [rip + \label]
    mov rdx, \labellen
    lea rcx, [rip + \context]
    mov r8, \ctxlen
    lea r9, [rip + okmbuf]
    push \outlen
    call \fn
    add rsp, 8
    lea rdi, [rip + okmbuf]
    lea rsi, [rip + \expect]
    mov rdx, \outlen
    call expect_b
.endm

.macro HKDF_DS_CHECK fn, secret, label, labellen, context, ctxlen, hlen, expect
    lea rdi, [rip + \secret]
    lea rsi, [rip + \label]
    mov rdx, \labellen
    lea rcx, [rip + \context]
    mov r8, \ctxlen
    lea r9, [rip + okmbuf]
    call \fn
    lea rdi, [rip + okmbuf]
    lea rsi, [rip + \expect]
    mov rdx, \hlen
    call expect_b
.endm

