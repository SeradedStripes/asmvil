# expect_b(rdi=got, rsi=want, rdx=len) - byte-wise compare, exit 1 on mismatch
expect_b:
    push rbx
    push r12
    push r13
    mov r12, rdi
    mov r13, rsi
    mov rbx, rdx
0:
    test rbx, rbx
    jz 1f
    movzx rax, byte ptr [r12]
    movzx rcx, byte ptr [r13]
    cmp rax, rcx
    jne fail
    inc r12
    inc r13
    dec rbx
    jmp 0b
1:
    pop r13
    pop r12
    pop rbx
    ret

