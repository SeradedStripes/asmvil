# AES-GCM vectors plus partial, streaming and verification tests.

.global _start

.macro CHECK dat, exp, n
    lea rdi, [rip + \dat]
    lea rsi, [rip + \exp]
    mov rdx, \n
    call expect
.endm

.macro INIT key, nr, iv
    lea rdi, [rip + ctx]
    lea rsi, [rip + \key]
    mov edx, \nr
    lea rcx, [rip + \iv]
    call gcm_init
    test al, al
    jz fail
.endm

.macro AAD dat, n
    lea rdi, [rip + ctx]
    lea rsi, [rip + \dat]
    mov rdx, \n
    call gcm_update_aad
    test al, al
    jz fail
.endm

.macro SEAL src, dst, n
    lea rdi, [rip + ctx]
    lea rsi, [rip + \src]
    lea rdx, [rip + \dst]
    mov rcx, \n
    call gcm_seal
    test al, al
    jz fail
.endm

.macro OPEN src, dst, n
    lea rdi, [rip + ctx]
    lea rsi, [rip + \src]
    lea rdx, [rip + \dst]
    mov rcx, \n
    call gcm_open
    test al, al
    jz fail
.endm

.macro FINAL dst
    lea rdi, [rip + ctx]
    lea rsi, [rip + \dst]
    call gcm_final_tag
    test al, al
    jz fail
.endm

.section .text
_start:
    lea rdi, [rip + pt256]
    xor ecx, ecx
.Lfill_pt256:
    mov eax, ecx
    imul eax, eax, 7
    add eax, 13
    mov BYTE PTR [rdi + rcx], al
    inc ecx
    cmp ecx, 160
    jb .Lfill_pt256

    # Empty plaintext and AAD. Finalization is idempotent.
    INIT key0, 10, iv0
    FINAL tag_out
    CHECK tag_out, tag_case1, 16
    FINAL tag_out
    CHECK tag_out, tag_case1, 16

    # One full block and constant-time verification.
    INIT key0, 10, iv0
    SEAL zero_pt, out, 16
    CHECK out, ct_case2, 16
    lea rdi, [rip + ctx]
    lea rsi, [rip + tag_case2]
    call gcm_verify
    cmp eax, 1
    jne fail
    FINAL tag_out
    CHECK tag_out, tag_case2, 16
    lea rdi, [rip + ctx]
    lea rsi, [rip + bad_tag]
    call gcm_verify
    test eax, eax
    jnz fail

    # Split 17-byte AAD, including a zero-length update, and four text blocks.
    INIT key3, 10, iv3
    AAD aad17, 1
    AAD key0, 0
    AAD aad17 + 1, 16
    SEAL pt3, out, 64
    CHECK out, ct3, 64
    FINAL tag_out
    CHECK tag_out, tag_case4, 16

    # Partial ciphertext blocks around the 16-byte boundary.
    INIT key0, 10, iv0
    SEAL zero_pt, out, 1
    CHECK out, ct_partial1, 1
    FINAL tag_out
    CHECK tag_out, tag_partial1, 16

    INIT key0, 10, iv0
    SEAL zero_pt, out, 15
    CHECK out, ct_partial15, 15
    FINAL tag_out
    CHECK tag_out, tag_partial15, 16

    INIT key0, 10, iv0
    SEAL zero_pt, out, 17
    CHECK out, ct_partial17, 17
    FINAL tag_out
    CHECK tag_out, tag_partial17, 16

    INIT key0, 10, iv0
    SEAL zero_pt, out, 31
    CHECK out, ct_partial31, 31
    FINAL tag_out
    CHECK tag_out, tag_partial31, 16

    # AAD and ciphertext are both partial blocks.
    INIT key3, 10, iv3
    AAD aad17, 17
    SEAL zero_pt, out, 1
    CHECK out, ct_aad17one, 1
    FINAL tag_out
    CHECK tag_out, tag_aad17one, 16

    # AES-256 GCM over ten complete blocks.
    INIT key256, 14, iv256
    AAD aad20, 20
    SEAL pt256, out, 160
    CHECK out, ct256, 160
    FINAL tag_out
    CHECK tag_out, tag256, 16

    # Complete a buffered block in a later call, then leave another tail.
    INIT key0, 10, iv0
    SEAL pt256, out, 15
    SEAL pt256 + 15, out + 15, 0
    SEAL pt256 + 15, out + 15, 8
    CHECK out, ct_split23, 23
    FINAL tag_out
    CHECK tag_out, tag_split23, 16

    # Open hashes ciphertext, not the emitted plaintext.
    INIT key3, 10, iv3
    OPEN ct3, out, 64
    CHECK out, pt3, 64
    FINAL tag_out
    CHECK tag_out, tag_case3, 16

    # Invalid round counts are rejected and cannot verify a tag.
    lea rdi, [rip + ctx]
    lea rsi, [rip + key0]
    mov edx, 12
    lea rcx, [rip + iv0]
    call gcm_init
    test al, al
    jnz fail
    lea rdi, [rip + ctx]
    lea rsi, [rip + key0]
    call gcm_verify
    test eax, eax
    jnz fail

    mov rax, SYS_EXIT
    xor edi, edi
    syscall

fail:
    mov rax, SYS_EXIT
    mov edi, 1
    syscall

expect:
    test rdx, rdx
    jz .Lexpect_done
.Lexpect_next:
    mov al, BYTE PTR [rdi]
    cmp al, BYTE PTR [rsi]
    jne fail
    inc rdi
    inc rsi
    dec rdx
    jnz .Lexpect_next
.Lexpect_done:
    ret

