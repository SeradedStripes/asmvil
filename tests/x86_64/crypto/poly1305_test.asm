# RFC 8439 Poly1305 example and reduction-vector tests.

.global _start

.macro CHECK dat, exp, n
    lea rdi, [rip + \dat]
    lea rsi, [rip + \exp]
    mov rdx, \n
    call expect
.endm

.macro INIT key
    lea rdi, [rip + ctx]
    lea rsi, [rip + \key]
    call poly1305_init
.endm

.macro UPDATE msg, n
    lea rdi, [rip + ctx]
    lea rsi, [rip + \msg]
    mov rdx, \n
    call poly1305_update
    test al, al
    jz fail
.endm

.macro FINAL
    lea rdi, [rip + ctx]
    lea rsi, [rip + tag_out]
    call poly1305_final
    test al, al
    jz fail
.endm

.macro RUN key, msg, n, tag
    INIT \key
    UPDATE \msg, \n
    FINAL
    CHECK tag_out, \tag, 16
.endm

.section .text
_start:
    # RFC 8439 section 2.5.2.
    RUN key_rfc, msg_rfc, 34, tag_rfc

    # A 15+1 boundary, zero-length update, and partial final block.
    INIT key_rfc
    UPDATE msg_rfc, 15
    UPDATE msg_rfc + 15, 0
    UPDATE msg_rfc + 15, 1
    UPDATE msg_rfc + 16, 18
    FINAL
    CHECK tag_out, tag_rfc, 16

    # Byte-at-a-time updates produce the same tag.
    INIT key_rfc
    lea r12, [rip + msg_rfc]
    mov r13d, 34
.Lbyte_updates:
    lea rdi, [rip + ctx]
    mov rsi, r12
    mov edx, 1
    call poly1305_update
    test al, al
    jz fail
    inc r12
    dec r13d
    jnz .Lbyte_updates
    FINAL
    CHECK tag_out, tag_rfc, 16

    # Verification finalizes, finalization is idempotent, and updates stop.
    INIT key_rfc
    UPDATE msg_rfc, 34
    lea rdi, [rip + ctx]
    lea rsi, [rip + tag_rfc]
    call poly1305_verify
    cmp eax, 1
    jne fail
    FINAL
    CHECK tag_out, tag_rfc, 16
    lea rdi, [rip + ctx]
    lea rsi, [rip + bad_tag]
    call poly1305_verify
    test eax, eax
    jnz fail
    lea rdi, [rip + ctx]
    lea rsi, [rip + msg_rfc]
    mov edx, 1
    call poly1305_update
    test al, al
    jnz fail

    # Empty messages produce the additive pad directly.
    INIT key_rfc
    FINAL
    CHECK tag_out, key_rfc + 16, 16

    # RFC 8439 Appendix A.3 vectors 5 through 11.
    RUN key_r2_s0, msg5, 16, tag3
    RUN key_r2_sff, msg6, 16, tag3
    RUN key_r1_s0, msg7, 48, tag5
    RUN key_r1_s0, msg8, 48, tag0
    RUN key_r2_s0, msg9, 16, tag9
    RUN key_r10_s0, msg10, 64, tag10
    RUN key_r10_s0, msg10, 48, tag11

    mov rax, SYS_EXIT
    xor edi, edi
    syscall

fail:
    mov rax, SYS_EXIT
    mov edi, 1
    syscall

expect:
    test rdx, rdx
    jz .Lexpect_done
.Lexpect_next:
    mov al, BYTE PTR [rdi]
    cmp al, BYTE PTR [rsi]
    jne fail
    inc rdi
    inc rsi
    dec rdx
    jnz .Lexpect_next
.Lexpect_done:
    ret

